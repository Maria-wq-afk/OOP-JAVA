public class lecture10 {
    public static void main(String[] args) {
        int x=1;
        while(x<=100){
            System.out.println(x);
            x=x+5;
        }

        int sum=0;
        int i=5;
        while(i<=100){
            sum=sum+i;
            i=i+5;
        }
        System.out.println("Sum is:"+sum);
    }
    
}
