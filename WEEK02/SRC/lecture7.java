public class lecture7 {
    public static void main(String[] args) {
        int x=3;
        switch(x){
            case 1:
                System.out.println("Bangladesh");
                break;
            case 2:
                System.out.println("USA");
                break;
            default:
                System.out.println("Out of earth");
                break;
        }


        char y='b';
        switch(y){
            case 'a':
                System.out.println("Bangladesh");
                break;
            case 'b':
                System.out.println("USA");
                break;
            default:
                System.out.println("Out of earth");
                break;
        }
    }
}
